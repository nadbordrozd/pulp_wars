function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** The entries of `words` that occur in `text` as whole words. */
export function wordsFoundV1(text: string, words: readonly string[]): string[] {
  const lower = text.toLowerCase();
  return words.filter((word) =>
    new RegExp(
      `(?<![\\p{L}\\p{N}])${escapeRegExp(word)}(?![\\p{L}\\p{N}])`,
      "u",
    ).test(lower),
  );
}

interface PromptTextsV1 {
  readonly label: string;
  readonly style: string;
  readonly structure: readonly string[];
  readonly exclude: string;
  readonly long: string;
  readonly tempo: ThemeTempoV1;
  readonly promptVersion: number;
}

function checkPromptTexts(
  shared: ThemeSharedV1,
  texts: PromptTextsV1,
  problems: string[],
): void {
  const { label } = texts;
  const { budgets } = shared;
  if (texts.style.length > budgets.sunoStyleChars) {
    problems.push(
      `${label}: the Suno style string is ${texts.style.length} characters, over the budget of ${budgets.sunoStyleChars}`,
    );
  }
  if (texts.exclude.length > budgets.sunoExcludeChars) {
    problems.push(
      `${label}: the Suno exclude string is ${texts.exclude.length} characters, over the budget of ${budgets.sunoExcludeChars}`,
    );
  }
  if (texts.long.length > budgets.longPromptChars) {
    problems.push(
      `${label}: the long prompt is ${texts.long.length} characters, over the budget of ${budgets.longPromptChars}`,
    );
  }
  if (texts.style.trim() === "" || texts.long.trim() === "") {
    problems.push(`${label}: a prompt is empty`);
  }
  if (!/(^|, )instrumental(,|$)/.test(texts.style)) {
    problems.push(
      `${label}: the Suno style string lacks the tag "instrumental"`,
    );
  }
  if (!/(^|, )vocals(,|$)/.test(texts.exclude)) {
    problems.push(`${label}: the Suno exclude string lacks the tag "vocals"`);
  }
  if (!texts.long.includes(shared.instrumentalSentence)) {
    problems.push(
      `${label}: the long prompt lacks the sentence "${shared.instrumentalSentence}"`,
    );
  }
  if (/[\n\r]/.test(texts.long)) {
    problems.push(`${label}: the long prompt is not one paragraph`);
  }
  if (!texts.long.includes(shared.motif)) {
    problems.push(
      `${label}: the long prompt does not name the shared opening, "${shared.motif}"`,
    );
  }
  if (texts.structure.length === 0 || texts.structure[0] !== "[Instrumental]") {
    problems.push(
      `${label}: the structure block must start with the line [Instrumental]`,
    );
  }
  for (const line of texts.structure) {
    if (!/^\[[^[\]]+\]$/.test(line)) {
      problems.push(
        `${label}: the structure line "${line}" has text outside one pair of brackets (a service would sing it)`,
      );
    }
  }
  // The one sentence that forbids vocals is the only place they are named.
  const positive = [
    texts.style.replace(/(^|, )instrumental(?=,|$)/, ""),
    ...texts.structure.filter((line) => line !== "[Instrumental]"),
    texts.long.split(shared.instrumentalSentence).join(" "),
  ];
  const vocal = wordsFoundV1(positive.join("\n"), THEME_VOCAL_WORDS_V1);
  if (vocal.length > 0) {
    problems.push(
      `${label}: a prompt asks for a voice (${vocal.join(", ")}); describe instruments only`,
    );
  }
  const all = [texts.style, ...texts.structure, texts.exclude, texts.long].join(
    "\n",
  );
  const named = wordsFoundV1(all, THEME_NAME_DENYLIST_V1);
  if (named.length > 0) {
    problems.push(
      `${label}: a prompt names an artist or a franchise (${named.join(", ")}); describe the sound instead`,
    );
  }
  const imitation = wordsFoundV1(all, THEME_IMITATION_PHRASES_V1);
  if (imitation.length > 0) {
    problems.push(
      `${label}: a prompt asks for an imitation (${imitation.join(", ")}); describe the sound instead`,
    );
  }
  const { tempo } = texts;
  if (
    !(tempo.min <= tempo.target && tempo.target <= tempo.max) ||
    tempo.min <= 0
  ) {
    problems.push(`${label}: the tempo target is outside its range`);
  }
  if (!Number.isInteger(texts.promptVersion) || texts.promptVersion < 1) {
    problems.push(`${label}: promptVersion must be a whole number from 1`);
  }
}

/** The least two themes of one metre may differ by, in beats per minute. */
export const THEME_MIN_TEMPO_GAP_BPM_V1 = 10;

/**
 * Everything wrong with the data, as sentences; empty when it is sound.
 * `factions` is the game's list (a test passes another to prove the checks).
 */
export function validateThemePromptsV1(
  data: ThemePromptsV1,
  factions: readonly ThemeFactionV1[] = GAME_THEME_FACTIONS_V1,
): string[] {
  const problems: string[] = [];
  if (data.schemaVersion !== THEME_PROMPTS_SCHEMA_VERSION) {
    problems.push(
      `schemaVersion is ${String(data.schemaVersion)}, expected ${THEME_PROMPTS_SCHEMA_VERSION}`,
    );
  }
  const { shared } = data;
  if (!Number.isInteger(shared.version) || shared.version < 1) {
    problems.push("shared.version must be a whole number from 1");
  }
  if (
    !shared.longPromptTail.includes(`${shared.length.targetSeconds} seconds`)
  ) {
    problems.push(
      `shared.longPromptTail does not state the target length, "${shared.length.targetSeconds} seconds"`,
    );
  }
  const known = new Map(factions.map((faction) => [faction.id, faction]));
  for (const faction of factions) {
    if (data.factions[faction.id] === undefined) {
      problems.push(
        `${faction.id}: the faction exists in the game and has no theme prompt`,
      );
    }
  }
  const themeIds = new Set<string>();
  for (const [key, entry] of Object.entries(data.factions)) {
    const faction = known.get(key);
    if (faction === undefined) {
      problems.push(
        `${key}: a theme prompt for a faction the game does not have`,
      );
      continue;
    }
    if (entry.name !== faction.name) {
      problems.push(
        `${key}: the name "${entry.name}" is not the game's name, "${faction.name}"`,
      );
    }
    const name = themeNameV1(faction.name);
    if (entry.themeId !== `theme.${name}`) {
      problems.push(`${key}: the theme id must be "theme.${name}"`);
    }
    const file = shared.outputFilePattern.replace("<name>", name);
    if (entry.outputFile !== file) {
      problems.push(`${key}: the output file must be "${file}"`);
    }
    if (themeIds.has(entry.themeId)) {
      problems.push(`${key}: the theme id "${entry.themeId}" is used twice`);
    }
    themeIds.add(entry.themeId);
    for (const part of ["lead", "rhythm", "colour"] as const) {
      if (entry.palette[part].length === 0) {
        problems.push(`${key}: the palette has no ${part} instrument`);
      }
    }
    if (entry.mood.length === 0 || entry.identity.trim() === "") {
      problems.push(`${key}: the identity or the mood words are missing`);
    }
    checkPromptTexts(
      shared,
      {
        label: key,
        style: sunoStyleV1(shared, entry),
        structure: entry.sunoStructure,
        exclude: sunoExcludeV1(shared, entry),
        long: longPromptV1(shared, entry),
        tempo: entry.tempo,
        promptVersion: entry.promptVersion,
      },
      problems,
    );
  }
  // Two themes are never confused: same metre means clearly different tempo.
  const entries = Object.entries(data.factions);
  entries.forEach(([key, entry], index) => {
    for (const [otherKey, other] of entries.slice(index + 1)) {
      if (
        entry.metre.signature === other.metre.signature &&
        Math.abs(entry.tempo.target - other.tempo.target) <
          THEME_MIN_TEMPO_GAP_BPM_V1
      ) {
        problems.push(
          `${key} and ${otherKey}: both are in ${entry.metre.signature} and their tempos are less than ${THEME_MIN_TEMPO_GAP_BPM_V1} BPM apart`,
        );
      }
    }
  });
  const extraIds = new Set<string>();
  for (const extra of data.extras) {
    if (extraIds.has(extra.id) || themeIds.has(extra.id)) {
      problems.push(`${extra.id}: the id is used twice`);
    }
    extraIds.add(extra.id);
    checkPromptTexts(
      shared,
      {
        label: extra.id,
        style: extra.sunoStyle,
        structure: extra.sunoStructure,
        exclude: extra.sunoExclude,
        long: extra.longPrompt,
        tempo: extra.tempo,
        promptVersion: extra.promptVersion,
      },
      problems,
    );
  }
  return problems;
}

function beatsPerBar(signature: string): number {
  const [count, unit] = signature.split("/").map(Number);
  if (count === undefined || unit === undefined) return 4;
  // Compound time (6/8, 12/8) is counted in dotted beats.
  return unit === 8 && count % 3 === 0 ? count / 3 : count;
}

/**
 * A loop length near the target: a whole number of eight-bar phrases at the
 * target tempo.
 */
export function suggestedLoopV1(
  tempo: ThemeTempoV1,
  metre: ThemeMetreV1,
  targetSeconds: number,
): { readonly bars: number; readonly seconds: number } {
  const barSeconds = (beatsPerBar(metre.signature) * 60) / tempo.target;
  const bars = Math.max(8, Math.round(targetSeconds / barSeconds / 8) * 8);
  return { bars, seconds: Math.round(bars * barSeconds * 10) / 10 };
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|");
}

function table(header: readonly string[], rows: readonly string[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

function fence(text: string): string {
  return ["```text", text, "```"].join("\n");
}

function tempoText(tempo: ThemeTempoV1): string {
  const beat = tempo.beat === "quarter" ? "" : ` (${tempo.beat} beat)`;
  return `${tempo.target} BPM${beat}, accept ${tempo.min}–${tempo.max}`;
}

function promptBlocks(
  style: string,
  structure: readonly string[],
  exclude: string,
  long: string,
): string[] {
  return [
    `**Suno, style of music** (${style.length} characters):`,
    fence(style),
    "**Suno, structure tags for the lyrics field:**",
    fence(structure.join("\n")),
    `**Suno, exclude styles** (${exclude.length} characters):`,
    fence(exclude),
    `**ElevenLabs Music, prompt** (${long.length} characters):`,
    fence(long),
  ];
}

/**
 * The generated part of the document: the shared fragments, the comparison
 * table and every prompt in full, formatted as the repository formats
 * Markdown.
 */
export async function renderThemePromptSectionV1(
  data: ThemePromptsV1,
): Promise<string> {
  const { shared } = data;
  const entries = Object.entries(data.factions);
  const parts: string[] = [
    "### Shared fragments",
    `Schema version ${data.schemaVersion}; shared fragments version ${shared.version}. Budgets: Suno style ${shared.budgets.sunoStyleChars} characters, Suno exclude ${shared.budgets.sunoExcludeChars} characters, long prompt ${shared.budgets.longPromptChars} characters. Length: ${shared.length.targetSeconds} seconds, accept ${shared.length.minSeconds}–${shared.length.maxSeconds}. The shared opening: a ${shared.motif}.`,
    "Appended to every faction's Suno style tags:",
    fence(shared.sunoCommonStyle),
    "Put before every faction's Suno exclude tags:",
    fence(shared.sunoCommonExclude),
    "Appended to every faction's long prompt:",
    fence(`${shared.instrumentalSentence} ${shared.longPromptTail}`),
    "### Comparison table",
    table(
      ["Faction", "Tempo", "Metre", "Lead", "Rhythm", "Mood", "Suggested loop"],
      entries.map(([, entry]) => {
        const loop = suggestedLoopV1(
          entry.tempo,
          entry.metre,
          shared.length.targetSeconds,
        );
        return [
          entry.name,
          `${entry.tempo.target} BPM`,
          `${entry.metre.signature}, ${entry.metre.feel}`,
          entry.palette.lead.join(", "),
          entry.palette.rhythm.join(", "),
          entry.mood.join(", "),
          `${loop.bars} bars, ${loop.seconds} s`,
        ];
      }),
    ),
  ];
  for (const [key, entry] of entries) {
    const style = sunoStyleV1(shared, entry);
    const exclude = sunoExcludeV1(shared, entry);
    const long = longPromptV1(shared, entry);
    parts.push(
      `### ${entry.name} (\`${key}\`)`,
      entry.identity,
      table(
        ["Field", "Value"],
        [
          [
            "Prompt version",
            `\`${promptVersionIdV1(shared, key, entry.promptVersion)}\``,
          ],
          ["Theme id", `\`${entry.themeId}\``],
          ["Output file", `\`${entry.outputFile}\``],
          ["Tempo", tempoText(entry.tempo)],
          ["Metre", `${entry.metre.signature}, ${entry.metre.feel}`],
          ["Mode", entry.mode],
          ["Lead", entry.palette.lead.join(", ")],
          ["Rhythm section", entry.palette.rhythm.join(", ")],
          ["Colour", entry.palette.colour.join(", ")],
          ["Mood", entry.mood.join(", ")],
          ["Duration", `${shared.length.targetSeconds} seconds`],
        ],
      ),
      ...promptBlocks(style, entry.sunoStructure, exclude, long),
    );
  }
  parts.push(
    "### Extras: title theme and stingers",
    "These are proposals, not part of the faction set: see [Optional extras](#optional-extras-a-proposal). Their strings are complete as stored; the shared fragments are not added.",
  );
  for (const extra of data.extras) {
    parts.push(
      `#### ${extra.name} (\`${extra.id}\`)`,
      extra.use,
      table(
        ["Field", "Value"],
        [
          [
            "Prompt version",
            `\`${promptVersionIdV1(shared, extra.id, extra.promptVersion)}\``,
          ],
          ["Output file", `\`${extra.outputFile}\``],
          ["Tempo", tempoText(extra.tempo)],
          ["Metre", `${extra.metre.signature}, ${extra.metre.feel}`],
          ["Loops", extra.loop ? "yes" : "no"],
          ["Duration", `${extra.durationSeconds} seconds`],
        ],
      ),
      ...promptBlocks(
        extra.sunoStyle,
        extra.sunoStructure,
        extra.sunoExclude,
        extra.longPrompt,
      ),
    );
  }
  const formatted = await format(parts.join("\n\n"), { parser: "markdown" });
  return formatted.trimEnd();
}

/** The text between the document's markers, or null when they are missing. */
export function generatedSectionV1(doc: string): string | null {
  const begin = doc.indexOf(THEME_SECTION_BEGIN);
  const end = doc.indexOf(THEME_SECTION_END);
  if (begin < 0 || end < begin) return null;
  return doc.slice(begin + THEME_SECTION_BEGIN.length, end).trim();
}

/** The document with `section` between its markers. */
export function withGeneratedSectionV1(doc: string, section: string): string {
  const begin = doc.indexOf(THEME_SECTION_BEGIN);
  const end = doc.indexOf(THEME_SECTION_END);
  if (begin < 0 || end < begin) {
    throw new Error("The document has no theme-prompts markers.");
  }
  return `${doc.slice(0, begin + THEME_SECTION_BEGIN.length)}\n\n${section}\n\n${doc.slice(end)}`;
}

async function main(command: string | undefined): Promise<number> {
  if (command !== "render" && command !== "check") {
    process.stderr.write("Usage: theme-prompts.ts <render|check>\n");
    return 2;
  }
  const data = await loadThemePromptsV1();
  const problems = validateThemePromptsV1(data);
  if (problems.length > 0) {
    process.stderr.write(`${problems.join("\n")}\n`);
    return 1;
  }
  const section = await renderThemePromptSectionV1(data);
  const doc = await readFile(THEME_MUSIC_DOC_PATH, "utf8");
  if (command === "render") {
    const next = withGeneratedSectionV1(doc, section);
    if (next !== doc) await writeFile(THEME_MUSIC_DOC_PATH, next);
    process.stdout.write(
      next === doc
        ? "docs/audio/THEME_MUSIC.md is up to date.\n"
        : "docs/audio/THEME_MUSIC.md rewritten.\n",
    );
    return 0;
  }
  if (generatedSectionV1(doc) !== section) {
    process.stderr.write(
      "docs/audio/THEME_MUSIC.md is out of date: run `npm run audio:theme-prompts -- render`.\n",
    );
    return 1;
  }
  process.stdout.write(
    `Theme prompts are sound: ${Object.keys(data.factions).length} factions, ${data.extras.length} extras.\n`,
  );
  return 0;
}

if (
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = await main(process.argv[2]);
}
