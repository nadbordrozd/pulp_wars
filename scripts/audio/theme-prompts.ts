export interface ThemeTempoV1 {
  readonly min: number;
  readonly max: number;
  readonly target: number;
  /** The note that gets the beat: "quarter", or "dotted quarter" in 6/8. */
  readonly beat: string;
}

export interface ThemeMetreV1 {
  readonly signature: string;
  readonly feel: string;
}

export interface ThemeSharedV1 {
  /** Bumped when a shared fragment below changes. */
  readonly version: number;
  readonly budgets: {
    readonly sunoStyleChars: number;
    readonly sunoExcludeChars: number;
    readonly longPromptChars: number;
  };
  readonly length: {
    readonly targetSeconds: number;
    readonly minSeconds: number;
    readonly maxSeconds: number;
  };
  readonly outputFilePattern: string;
  /** The opening figure every theme shares; every long prompt names it. */
  readonly motif: string;
  /** Appended to every faction's Suno style tags. */
  readonly sunoCommonStyle: string;
  /** Prepended to every faction's Suno exclude tags. */
  readonly sunoCommonExclude: string;
  /** The one sentence that may name vocals: it forbids them. */
  readonly instrumentalSentence: string;
  /** Appended to every faction's long prompt after that sentence. */
  readonly longPromptTail: string;
}

export interface ThemeFactionPromptV1 {
  /** The player-facing faction name, as the game shows it. */
  readonly name: string;
  readonly themeId: string;
  readonly outputFile: string;
  /** Bumped when any prompt text of this entry changes. */
  readonly promptVersion: number;
  readonly identity: string;
  readonly palette: {
    readonly lead: readonly string[];
    readonly rhythm: readonly string[];
    readonly colour: readonly string[];
  };
  readonly tempo: ThemeTempoV1;
  readonly metre: ThemeMetreV1;
  readonly mode: string;
  readonly mood: readonly string[];
  /** The faction's own tags; `sunoStyleV1` adds the shared ones. */
  readonly sunoStyle: string;
  /** Bracketed section tags, one per line, with no words outside brackets. */
  readonly sunoStructure: readonly string[];
  /** The faction's own exclusions; `sunoExcludeV1` adds the shared ones. */
  readonly sunoExclude: string;
  /** The faction's own paragraph; `longPromptV1` adds the shared ending. */
  readonly longPrompt: string;
}

/** A title theme or a stinger: its strings are complete as stored. */
export interface ThemeExtraPromptV1 {
  readonly id: string;
  readonly name: string;
  readonly use: string;
  readonly outputFile: string;
  readonly loop: boolean;
  readonly durationSeconds: number;
  readonly promptVersion: number;
  readonly tempo: ThemeTempoV1;
  readonly metre: ThemeMetreV1;
  readonly sunoStyle: string;
  readonly sunoStructure: readonly string[];
  readonly sunoExclude: string;
  readonly longPrompt: string;
}

export interface ThemePromptsV1 {
  readonly schemaVersion: number;
  readonly shared: ThemeSharedV1;
  readonly factions: Readonly<Record<string, ThemeFactionPromptV1>>;
  readonly extras: readonly ThemeExtraPromptV1[];
}

/** A faction of the game: its id and the name the player reads. */
export interface ThemeFactionV1 {
  readonly id: string;
  readonly name: string;
}

/** The factions the game has today, from the engine. */
