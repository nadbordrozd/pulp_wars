  FACTION_IDS_V7.map((id) => ({ id, name: FACTION_DISPLAY_NAMES_V7[id] }));

export async function loadThemePromptsV1(): Promise<ThemePromptsV1> {
  return JSON.parse(
    await readFile(THEME_PROMPTS_DATA_PATH, "utf8"),
  ) as ThemePromptsV1;
}

/** The text for Suno's style field: the faction's tags, then the shared. */
export function sunoStyleV1(
  shared: ThemeSharedV1,
  entry: ThemeFactionPromptV1,
): string {
  return `${entry.sunoStyle}, ${shared.sunoCommonStyle}`;
}

/** The text for Suno's exclude field: the shared tags, then the faction's. */
export function sunoExcludeV1(
  shared: ThemeSharedV1,
  entry: ThemeFactionPromptV1,
): string {
  return `${shared.sunoCommonExclude}, ${entry.sunoExclude}`;
}

/** The one-paragraph prompt for a service that takes a description. */
export function longPromptV1(
  shared: ThemeSharedV1,
  entry: ThemeFactionPromptV1,
): string {
  return `${entry.longPrompt} ${shared.instrumentalSentence} ${shared.longPromptTail}`;
}

/** What a generation record cites: "UNDEAD@1+s1". */
export function promptVersionIdV1(
  shared: ThemeSharedV1,
  key: string,
  promptVersion: number,
): string {
  return `${key}@${promptVersion}+s${shared.version}`;
}

/** "ICE_FOLK" names its theme "ice-folk", from the player-facing name. */
export function themeNameV1(displayName: string): string {
  return displayName.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

